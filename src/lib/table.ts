// 그리지 않는다. 값이 하나라도 생기면 자동으로 다시 나타난다.
// 워크플로 상태(적용 여부·상태·우선순위)처럼 "미정" 자체가 의미인 컬럼은
// 대상이 아니다 — 그건 빈 값이 아니라 판단 전 단계다.

/** 현재 행 집합에 이 컬럼 값이 하나라도 있는가. */
export function anyPresent<T>(rows: readonly T[], pick: (row: T) => unknown): boolean {
  return rows.some((row) => {
    const v = pick(row);
    return v !== null && v !== undefined && v !== "";
  });
}
