// 대략 맞기만 하면 된다. 다만 개명·폐지는 사람이 갱신해야 한다.
//   신에너지 및 재생에너지…      → 재생에너지 개발ㆍ이용ㆍ보급 촉진법
//   저탄소 녹색성장 기본법        → 기후위기 대응을 위한 탄소중립ㆍ녹색성장 기본법
//   기부금품의 모집 및 사용…      → 기부금품의 모집ㆍ사용 및 기부문화 활성화…
//   벤처기업육성에 관한 특별조치법 → 벤처기업육성에 관한 특별법
//   품질경영 및 공산품안전관리법   → 전기용품 및 생활용품 안전관리법
//   방송통신위원회의 설치 및 운영에 관한 법률 → 폐지 (대체 없음, 목록에서 제외)

