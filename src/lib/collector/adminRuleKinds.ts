// 10,249건만 들어왔다 — 코퍼스의 43%. 부트스트랩이 멈춘 게 아니라(커서
// 243/243 COMPLETED) 나머지를 의도적으로 버리고 있었다. "검색 miss 제로" 가
// 이 앱의 핵심 목표인데 절반 이상이 아예 없는 상태였다.
//
// 2026-08 표본 조사: 목록 10페이지를 코퍼스 전역에 흩뿌려 1,000건을 스캔하고,
// 종류별로 최대 14건씩 상세를 받아 실제 파서에 통과시켰다. 판정 기준은
// "조문 2개 이상으로 쪼개지는가" — 조문 단위 diff 가 이 제품의 핵심이라
// 한 덩어리로만 들어오는 문서는 넣어도 "본문 전체가 바뀜" 밖에 못 보여준다.
//
//   종류              코퍼스   조문 파싱   평균 조문
//   ─────────────────────────────────────────────────
//   고시(이미 수집)    40.6%    51.7%*      8.4*     (*운영 DB 10,249건 실측)
//   훈령              23.2%   100%        18.2
//   예규              17.4%    79%        19.4
//   내규               5.5%    93%        16.2
//   규정               2.8%   100%        12.0
//   규칙               1.1%   100%        18.7
//   국무총리훈령       1.0%   100%        12.9
//   공고               0.8%    75%        13.6
//   지침               0.7%    71%        17.4
//   대통령훈령         0.5%   100%        28.6
//   세칙               0.3%    67%         5.7
//   ─── 제외 ──────────────────────────────────────
//   등기예규           3.1%     7%         1.4
//   재판예규           1.4%    21%         4.2
//   가족관계등록예규   1.2%    17%         1.9
//   행정예규           0.4%    25%         1.8
//
// 즉 이미 받고 있던 고시보다 훈령·예규 쪽 구조가 오히려 낫다. 반대로 법원
// 계열 예규(등기·재판·가족관계등록)는 조문이 아니라 서술식 실무 지침이라
// 한 덩어리로만 들어오고, 애초에 기업 컴플라이언스가 지켜야 할 규범도 아니다.
//
// 화이트리스트가 아니라 제외 목록으로 뒤집었다. 화이트리스트는 법제처가 새
// 종류를 만들면 조용히 누락되는데, 그게 이번에 43% 를 잃은 방식이었다.
// 이제 모르는 종류는 일단 받고, 아니면 나중에 빼는 쪽으로 실패한다.

/** 조문 구조가 없어 조문 단위 diff 를 만들 수 없는 종류. */
export const EXCLUDED_ADMIN_RULE_KINDS = new Set([
  "등기예규",
  "재판예규",
  "가족관계등록예규",
  "행정예규",
]);

export function isCollectableAdminRuleKind(kind: string | null | undefined): boolean {
  if (!kind) return true; // 종류 미상은 일단 받는다. 버리는 쪽이 더 위험하다.
  return !EXCLUDED_ADMIN_RULE_KINDS.has(kind.trim());
}
