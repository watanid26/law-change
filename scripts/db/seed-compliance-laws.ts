async function main() {
  const groups = Object.entries(INDUSTRY_LAWS);
  const allNames = Array.from(new Set(groups.flatMap(([, laws]) => laws)));
  console.log(`[seed-industry] ${groups.length}개 산업군 · 총 ${allNames.length}개 법령(중복 제거) 시드 시작`);

  const t0 = Date.now();
  const report = await syncLawCatalog({
    queries: allNames,
    pageSize: 20,
    // 이름당 최대 2페이지(=40건) — 동명 시행령/시행규칙까지 포괄
    maxPages: 2,
  });

  const elapsed = Date.now() - t0;
  console.log(
    `[seed-industry] done in ${(elapsed / 1000).toFixed(1)}s — scanned=${report.scanned}, new=${report.newDocuments}, changed=${report.changedDocuments}, enqueued=${report.enqueued}`,
  );

  process.exit(0);
}

main().catch((err) => {
  console.error("[seed-industry] threw", err);
  process.exit(1);
});
